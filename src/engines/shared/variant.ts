import { makeRandom } from './random';

/**
 * Варианти на една и съща активност.
 *
 * Каталогът расте бавно — един JSON е един час работа. Но детето играе
 * същата карта по няколко пъти на седмица и запомня отговорите, вместо да
 * разбира правилото. Затова активността носи ЗАДАЧАТА, а вариантът я
 * преоблича: същото умение, същата трудност, друго съдържание.
 *
 * Правила, които всеки вариант спазва:
 *
 *   • Вариант 0 е точно това, което пише в JSON-а. Авторът вижда своето.
 *   • Вариантът не мени трудността — само подредбата и конкретните стойности
 *     в рамките, зададени от автора.
 *   • Едно и също `(id, variant)` дава един и същ резултат. Няма мигане при
 *     повторно изчертаване и проверката е възпроизводима.
 */

/** Стабилен хеш на низ. FNV-1a — кратък и с добро разпръскване. */
function hashString(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** Генераторът на случайност за конкретен вариант на конкретна активност. */
export function variantRandom(activityId: string, variant: number): () => number {
  // Умножението с нечетно число разнася съседните варианти далече един от
  // друг: вариант 1 и вариант 2 не трябва да си приличат.
  return makeRandom(hashString(activityId) + Math.imul(variant, 0x9e3779b1));
}
